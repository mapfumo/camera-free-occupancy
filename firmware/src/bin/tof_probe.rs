//! First light through the FFI: talk to the VL53L5CX using ST's ULD.
//!
//! `i2c_scan` proved the sensor acknowledges its address. That is the bus
//! working, not the driver. This is the first code that actually exercises the
//! chain the whole project rests on:
//!
//! ```text
//!   Rust  ->  vl53l5cx_is_alive()  [ST's C driver]
//!                   |
//!                   +-> VL53L5CX_RdByte / WrByte  [our Rust platform layer]
//!                             |
//!                             +-> Embassy blocking I2C  ->  the sensor
//! ```
//!
//! C calling back into Rust, across a boundary generated by bindgen, against a
//! real device. If the address-width conversion in the platform layer were
//! wrong, or the register addressing byte order reversed, this is where it
//! shows — `is_alive` would come back false with no other clue.
//!
//! `vl53l5cx_init` is the second and much heavier test: it pushes 86,017 bytes
//! of firmware into the sensor in three 32 KB `WrMulti` calls, which is the
//! only thing that exercises the merged-`Operation::Write` path at full size.
//! It takes a few hundred milliseconds and is where a subtly wrong bulk write
//! surfaces.
//!
//! Run with: `cargo run --release --bin tof_probe`

#![no_std]
#![no_main]

use defmt::{error, info};
use embassy_executor::Spawner;
use embassy_stm32::gpio::{Level, Output, Speed};
use embassy_stm32::i2c::I2c;
use embassy_stm32::time::Hertz;
use embassy_time::{Duration, Timer};

use defmt_rtt as _;
use panic_probe as _;

use coworkos_firmware::clock;
use coworkos_firmware::vl53l5cx::bindings::{
    VL53L5CX_Configuration, vl53l5cx_init, vl53l5cx_is_alive,
};
use coworkos_firmware::vl53l5cx::platform::BusContext;

/// The ULD's own default, in its 8-bit convention. The platform layer shifts
/// this down to 0x29 for Embassy — see `platform.rs`.
const DEFAULT_ADDRESS_8BIT: u16 = 0x52;

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = embassy_stm32::init(clock::config());

    info!("VL53L5CX first light — ULD via FFI");

    // PWR_EN on A5/PB0 enables the SATEL's regulator. Held for the whole
    // program: dropping this would cut power to the sensor mid-conversation.
    let _power = Output::new(p.PB0, Level::High, Speed::Low);
    Timer::after(Duration::from_millis(100)).await;

    let mut cfg = embassy_stm32::i2c::Config::default();
    cfg.frequency = Hertz::khz(100);
    // Generous next to the 50 ms used for scanning: firmware download moves
    // 32 KB in a single transaction and must not be cut off part-way.
    cfg.timeout = Duration::from_millis(1000);
    let i2c = I2c::new_blocking(p.I2C1, p.PB8, p.PB9, cfg);

    // Lives for the rest of the program. The ULD holds a raw pointer to it,
    // so it must not move or drop while any driver call can still run — which
    // is satisfied by `main` never returning.
    let mut bus = BusContext::new(i2c);

    // The ULD expects a zeroed configuration block it then owns. It is ~2.4 KB,
    // dominated by a 1 KB scratch buffer the driver uses for frame assembly.
    let mut dev: VL53L5CX_Configuration = unsafe { core::mem::zeroed() };
    dev.platform.address = DEFAULT_ADDRESS_8BIT;
    dev.platform.ctx = bus.as_ctx_ptr();

    // ---- is_alive: a handful of register reads, the cheapest real test ----
    let mut alive: u8 = 0;
    let status = unsafe { vl53l5cx_is_alive(&mut dev, &mut alive) };

    if status != 0 || alive == 0 {
        error!(
            "is_alive failed: status={=u8}, alive={=u8}",
            status, alive
        );
        error!("The bus works (i2c_scan sees 0x29), so suspect the platform");
        error!("layer: address width, or 16-bit register byte order.");
        loop {
            Timer::after(Duration::from_secs(60)).await;
        }
    }

    info!("is_alive OK — the FFI chain works end to end");
    info!("");

    // ---- init: uploads 86,017 bytes of firmware, takes a moment ----
    info!("downloading sensor firmware (86 KB, three 32 KB writes)...");
    let status = unsafe { vl53l5cx_init(&mut dev) };

    if status != 0 {
        error!("vl53l5cx_init failed: status={=u8}", status);
        error!("is_alive passed, so single-byte access is sound — this points");
        error!("at the bulk path: WrMulti's merged Operation::Write handling.");
        loop {
            Timer::after(Duration::from_secs(60)).await;
        }
    }

    info!("init OK — firmware downloaded and running");
    info!("");
    info!("Phase 1 milestone: ST's C driver is driving the sensor through");
    info!("a Rust platform layer. Next: resolution, ranging, and 8x8 frames.");

    loop {
        Timer::after(Duration::from_secs(60)).await;
    }
}
